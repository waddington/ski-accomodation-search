import { chromium } from "playwright";
import fs from "fs";
const [qs, out] = process.argv.slice(2);
const url = "https://www.mmv-holidays.co.uk/destinations/northern-french-alps/tignes/holiday-village-brevieres-winter?" + qs;
const browser = await chromium.launch({ headless: true, channel: "chrome" });
const ctx = await browser.newContext({ locale: "en-GB", viewport: { width: 1366, height: 900 } });
const page = await ctx.newPage();
const reqs = [];
ctx.on("response", async r => { const u=r.url(); if (/mmv/.test(u) && !/msr\.mmv|static\.mmv|itp-cookie/.test(u) && ["xhr","fetch","document"].includes(r.request().resourceType())) { let b=""; try{b=(await r.text()).slice(0,300)}catch{}; reqs.push(r.request().resourceType()+" "+u.slice(0,300)+"\n   "+b.replace(/\s+/g," ")); }});
await page.goto(url, { waitUntil: "domcontentloaded" });
await page.waitForTimeout(3000);
await page.getByRole("button", { name: /accept|accepter/i }).first().click().catch(()=>{});
await page.waitForTimeout(4000);
await page.evaluate(() => { document.querySelector("input[name=adults]").value = "8"; });
const btn = page.locator("#establishment-search-form button[type=submit], #establishment-search-form button:has-text('Book')").first();
console.log("btn count", await btn.count(), await btn.innerText().catch(()=>""));
await page.evaluate(() => { const ev = { preventDefault(){} }; window.handleEstablishmentSubmit({ checkoutUrl: '/checkout', propertyId: 16 }); }).catch(e=>console.log("eval", e.message));
const popup = null;
await page.waitForTimeout(10000);
const p2 = popup || page;
await p2.waitForTimeout(3000);
console.log("URL:", p2.url());
fs.writeFileSync(out + "/book.txt", await p2.innerText("body"));
await p2.screenshot({ path: out + "/book.png", fullPage: true });
console.log(reqs.join("\n"));
await browser.close();
